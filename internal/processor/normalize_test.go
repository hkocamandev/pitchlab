// The golden fixture is the highest-value test in this package.
//
// The Go processor and the Python training code both transform raw readings,
// and they have to agree exactly. If they drift, nothing errors -- the model
// simply starts receiving features that mean something slightly different from
// what it was trained on, and every score quietly stops being meaningful.
//
// The fixture is generated by running real pitches through the training-time
// feature code (ml/scripts/export_normalization_fixture.py). Changing
// features.py without regenerating it breaks this test, which is the point.

type goldenFile struct {
	Note           string       `json:"note"`
	SourceSnapshot string       `json:"source_snapshot"`
	Cases          []goldenCase `json:"cases"`
}

type goldenCase struct {
	Input    goldenInput               `json:"input"`
	Expected map[string]*float64OrBool `json:"expected"`
}

type goldenInput struct {
	PThrows   string   `json:"p_throws"`
	Stand     string   `json:"stand"`
	PitchType string   `json:"pitch_type"`
	Speed     *float64 `json:"release_speed"`
	SpinRate  *float64 `json:"release_spin_rate"`
	SpinAxis  *float64 `json:"spin_axis"`
	RelPosX   *float64 `json:"release_pos_x"`
	RelPosZ   *float64 `json:"release_pos_z"`
	Extension *float64 `json:"release_extension"`
	PfxX      *float64 `json:"pfx_x"`
	PfxZ      *float64 `json:"pfx_z"`
	PlateX    *float64 `json:"plate_x"`
	PlateZ    *float64 `json:"plate_z"`
	SzTop     *float64 `json:"sz_top"`
	SzBot     *float64 `json:"sz_bot"`
	ArmAngle  *float64 `json:"arm_angle"`
}

// float64OrBool accepts either, because in_zone is a boolean while everything
// else is numeric.
type float64OrBool struct {
	Num  *float64
	Bool *bool
}

func (v *float64OrBool) UnmarshalJSON(b []byte) error {
	if string(b) == "null" {
		return nil
	}
	var f float64
	if err := json.Unmarshal(b, &f); err == nil {
		v.Num = &f
		return nil
	}
	var bl bool
	if err := json.Unmarshal(b, &bl); err == nil {
		v.Bool = &bl
		return nil
	}
	return nil
}

func loadGolden(t *testing.T) goldenFile {
	t.Helper()
	path := filepath.Join("testdata", "normalization_golden.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Skipf("golden fixture not present; generate it with "+
			"ml/scripts/export_normalization_fixture.py (%v)", err)
	}
	var g goldenFile
	if err := json.Unmarshal(raw, &g); err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	if len(g.Cases) == 0 {
		t.Fatal("fixture has no cases")
	}
	return g
}

func (in goldenInput) toRaw() events.RawMeasurement {
	return events.RawMeasurement{
		PitchType:        in.PitchType,
		ReleaseSpeed:     in.Speed,
		ReleaseSpinRate:  in.SpinRate,
		SpinAxis:         in.SpinAxis,
		ReleasePosX:      in.RelPosX,
		ReleasePosZ:      in.RelPosZ,
		ReleaseExtension: in.Extension,
		PfxX:             in.PfxX,
		PfxZ:             in.PfxZ,
		PlateX:           in.PlateX,
		PlateZ:           in.PlateZ,
		SzTop:            in.SzTop,
		SzBot:            in.SzBot,
		ArmAngle:         in.ArmAngle,
	}
}

func TestNormalizationMatchesTheTrainingCode(t *testing.T) {
	golden := loadGolden(t)
	const tolerance = 1e-9

	for i, tc := range golden.Cases {
		norm := Normalize(tc.Input.toRaw(), tc.Input.PThrows, tc.Input.Stand)

		check := func(name string, got *float64) {
			t.Helper()
			want, present := tc.Expected[name]
			if !present || want == nil || want.Num == nil {
				if got != nil {
					t.Errorf("case %d (%s vs %s) %s: Go produced %.10f, Python produced nothing",
						i, tc.Input.PThrows, tc.Input.Stand, name, *got)
				}
				return
			}
			if got == nil {
				t.Errorf("case %d (%s vs %s) %s: Go produced nothing, Python produced %.10f",
					i, tc.Input.PThrows, tc.Input.Stand, name, *want.Num)
				return
			}
			if math.Abs(*got-*want.Num) > tolerance {
				t.Errorf("case %d (%s vs %s) %s: Go %.10f, Python %.10f (diff %.2e)",
					i, tc.Input.PThrows, tc.Input.Stand, name, *got, *want.Num,
					math.Abs(*got-*want.Num))
			}
		}

		check("pfx_x_arm", norm.PfxXArm)
		check("release_pos_x_arm", norm.ReleasePosXArm)
		check("plate_x_bat", norm.PlateXBat)
		check("zone_height_norm", norm.ZoneHeightNorm)

		if want, ok := tc.Expected["in_zone"]; ok && want != nil {
			var wantBool *bool
			switch {
			case want.Bool != nil:
				wantBool = want.Bool
			case want.Num != nil:
				b := *want.Num != 0
				wantBool = &b
			}
			if wantBool != nil && norm.InZone != nil && *norm.InZone != *wantBool {
				t.Errorf("case %d in_zone: Go %v, Python %v", i, *norm.InZone, *wantBool)
			}
		}

		// Spin encoding and zone distance are computed in the feature builder
		// rather than the normalizer, so they are checked through it.
		f := BuildFeatures(FeatureInput{
			Measurement: norm,
			Stand:       tc.Input.Stand,
			PThrows:     tc.Input.PThrows,
			PitchType:   tc.Input.PitchType,
		}, mlclient.VariantPitching)

		checkFeature := func(name string) {
			t.Helper()
			want, present := tc.Expected[name]
			if !present || want == nil || want.Num == nil {
				return
			}
			got, ok := f[name].(float64)
			if !ok {
				t.Errorf("case %d %s: Go did not produce the feature, Python produced %.10f",
					i, name, *want.Num)
				return
			}
			if math.Abs(got-*want.Num) > tolerance {
				t.Errorf("case %d (%s vs %s) %s: Go %.10f, Python %.10f",
					i, tc.Input.PThrows, tc.Input.Stand, name, got, *want.Num)
			}
		}
		checkFeature("spin_axis_sin")
		checkFeature("spin_axis_cos")
		checkFeature("dist_from_zone_center")
	}
}

func TestGoldenFixtureCoversBothHandednessCombinations(t *testing.T) {
	// A fixture of only right-on-right pitches would pass with the mirroring
	// inverted, which is exactly the bug that shipped once already.
	golden := loadGolden(t)

	seen := map[string]int{}
	for _, tc := range golden.Cases {
		seen[tc.Input.PThrows+tc.Input.Stand]++
	}
	for _, combo := range []string{"RR", "RL", "LR", "LL"} {
		if seen[combo] == 0 {
			t.Errorf("fixture has no %s pitcher vs %s batter case",
				string(combo[0]), string(combo[1]))
		}
	}
}

